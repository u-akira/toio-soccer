"""Flatten the project library modules into a single CircuitPython script."""

import argparse
import ast
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LIBRARIES = tuple(sorted(path.stem for path in (ROOT / "lib").glob("*.py")))
MAIN_MARKER = "# --- APPLICATION ENTRYPOINT ---"


def _local_module(node, names):
    return isinstance(node, ast.ImportFrom) and node.module is not None and \
        node.module.lstrip(".") in names


class _RemoveLocalImports(ast.NodeTransformer):
    def __init__(self, names):
        self.names = names

    def visit_ImportFrom(self, node):
        if _local_module(node, self.names):
            return None
        return node

    def visit_Try(self, node):
        local_try = all(_local_module(item, self.names) for item in node.body)
        local_handlers = all(
            all(_local_module(item, self.names) for item in handler.body)
            for handler in node.handlers
        )
        if local_try and local_handlers and not node.orelse and not node.finalbody:
            return None
        return self.generic_visit(node)


def _dependencies(module_name, tree):
    result = set()
    for node in ast.walk(tree):
        if _local_module(node, set(LIBRARIES)):
            result.add(node.module.lstrip("."))
    result.discard(module_name)
    return result


def _ordered_libraries():
    trees = {
        name: ast.parse((ROOT / "lib" / (name + ".py")).read_text(encoding="utf-8"))
        for name in LIBRARIES
    }
    ordered = []
    visiting = set()
    visited = set()

    def visit(name):
        if name in visited:
            return
        if name in visiting:
            raise ValueError("Circular library import: " + name)
        visiting.add(name)
        for dependency in sorted(_dependencies(name, trees[name])):
            if dependency not in trees:
                raise ValueError("Unknown local module: " + dependency)
            visit(dependency)
        visiting.remove(name)
        visited.add(name)
        ordered.append(name)

    for module_name in LIBRARIES:
        visit(module_name)
    return ordered, trees


def build_release(output_path):
    names = set(LIBRARIES)
    ordered, trees = _ordered_libraries()
    chunks = ["# Generated by tools/build_release.py. Do not edit this file.\n"]

    for module_name in ordered:
        transformed = _RemoveLocalImports(names).visit(trees[module_name])
        ast.fix_missing_locations(transformed)
        chunks.append("\n# --- bundled library: " + module_name + " ---\n")
        chunks.append(ast.unparse(transformed))
        chunks.append("\n")

    main_path = ROOT / "code.py"
    main_lines = main_path.read_text(encoding="utf-8").splitlines()
    main_tree = ast.parse("\n".join(main_lines))
    removed_lines = set()
    for node in ast.walk(main_tree):
        if _local_module(node, names):
            removed_lines.update(range(node.lineno, node.end_lineno + 1))
    main_source = "\n".join(
        line for line_number, line in enumerate(main_lines, 1)
        if line_number not in removed_lines
    )
    chunks.append("\n" + MAIN_MARKER + "\n")
    chunks.append(main_source.rstrip() + "\n")

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(chunks), encoding="utf-8", newline="\n")
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    arguments = parser.parse_args()
    output = build_release(arguments.output)
    print("Generated release:", output)


if __name__ == "__main__":
    main()
